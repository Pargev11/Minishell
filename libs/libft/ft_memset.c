#include "libft.h"

void	*ft_memset(void *b, int c, size_t len)
{
	unsigned char	*res;

	res = (unsigned char *)b;
	while (len > 0)
	{
		*res = (unsigned char)c;
		res++;
		len--;
	}
	return (b);
}
